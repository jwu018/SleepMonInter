"""Export what the web app's TypeScript copy of the processing needs from Python.

1. Band-pass filter coefficients for common sample rates (scipy designs them; TypeScript
   only applies them, so it doesn't need its own filter-design code).
2. A cross-check fixture: a synthetic trial CSV plus the Python pipeline's results on it.
   The web test runs the TypeScript pipeline on the same CSV and must get the same answer.

Run after changing anything in tools/processing:
    python export_web_processing.py
"""

from __future__ import annotations

import json
from dataclasses import replace
from datetime import datetime
from pathlib import Path

import numpy as np
from scipy.signal import butter, sosfilt_zi

from generate_synthetic import PROFILES, simulate_night, write_recording
from processing.load import load_trial
from processing.metrics import find_pauses, relative_amplitude, respiratory_rate_per_minute
from processing.pipeline import process_trial

ROOT = Path(__file__).resolve().parent.parent
WEB_PROCESSING = ROOT / "web" / "src" / "lib" / "processing"
SAMPLE_RATES_HZ = [5, 10, 12.5, 20, 25, 40, 50, 100]
BAND_HZ = (0.1, 1.0)
ORDER = 2


def export_coefficients() -> None:
    def table(btype: str, cutoff: object) -> dict[str, dict[str, list]]:
        out = {}
        for fs in SAMPLE_RATES_HZ:
            sos = butter(ORDER, cutoff, btype=btype, fs=fs, output="sos")
            out[str(fs)] = {"sos": sos.tolist(), "zi": sosfilt_zi(sos).tolist()}
        return out

    tables = {
        "BANDPASS": table("bandpass", BAND_HZ),  # breathing band
        "HIGHPASS": table("highpass", BAND_HZ[1]),  # noise band (SNR)
        "LOWPASS": table("lowpass", BAND_HZ[0]),  # interference band (SIR)
    }
    lines = [
        "// GENERATED by tools/export_web_processing.py: do not edit by hand.",
        f"// Butterworth band-pass, order {ORDER}, {BAND_HZ[0]}-{BAND_HZ[1]} Hz (scipy design).",
        "// sos rows are [b0, b1, b2, a0, a1, a2]; zi is scipy's sosfilt_zi (steady-state start).",
        "",
        f"export const BAND_HZ = [{BAND_HZ[0]}, {BAND_HZ[1]}] as const;",
        "",
        "export type Coefficients = Record<string, { sos: number[][]; zi: number[][] }>;",
        "",
    ]
    for name, t in tables.items():
        lines += [f"export const {name}: Coefficients = " + json.dumps(t, indent=2) + ";", ""]
    (WEB_PROCESSING / "filterCoefficients.ts").write_text("\n".join(lines), encoding="utf-8")


def export_fixture() -> None:
    fixtures = WEB_PROCESSING / "__fixtures__"
    fixtures.mkdir(parents=True, exist_ok=True)
    # A trial with everything the algorithm must cope with: artifacts, a pause, a glitch.
    profile = replace(PROFILES["stable"], pauses_per_hour=40, gaps_per_hour=0, no_signal_per_hour=0)
    night = simulate_night(profile, 180.0, np.random.default_rng(42))
    night.L_uH[1000] = 1970.216  # a glitch like the real belt's
    csv_path = fixtures / "S20261110_140000_fixture.csv"
    write_recording(
        night, csv_path, device_id="NN-DEV-01", start_local=datetime(2026, 11, 10, 14),
        extra_header={"synthetic": "true"},
    )  # fmt: skip

    trial = load_trial(csv_path)
    result = process_trial(trial, trim_start_s=10, trim_end_s=5)
    rr = respiratory_rate_per_minute(result.breaths, trial.fs_hz, len(trial.t_s))
    amp = relative_amplitude(result.filtered, result.breaths)
    expected = {
        "peak_idx": result.breaths.peak_idx.tolist(),
        "trough_idx": result.breaths.trough_idx.tolist(),
        "breath_count_trimmed": result.breath_count,
        "rate_bpm_trimmed": result.rate_bpm,
        "rate_per_minute": [None if np.isnan(v) else v for v in rr],
        "amplitude_median": float(np.median(amp)),
        "pauses": find_pauses(result.breaths, trial.fs_hz),
        # A few filtered values to check the filter numerically.
        "filtered_samples": {str(i): float(result.filtered[i]) for i in (0, 250, 1000, 2500, 4400)},
        "snr_db_trimmed": result.snr_db,
        "sir_db_trimmed": result.sir_db,
        "quality": [
            {"start_s": w.start_s, "snr_db": w.snr_db, "sir_db": w.sir_db, "label": w.label}
            for w in result.quality
        ],
    }
    (fixtures / "expected.json").write_text(json.dumps(expected, indent=1), encoding="utf-8")


if __name__ == "__main__":
    export_coefficients()
    export_fixture()
    print(f"Wrote {WEB_PROCESSING / 'filterCoefficients.ts'} and the cross-check fixture.")
